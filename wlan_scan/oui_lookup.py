def _load_cache() -> dict[str, str]:
    """Load the OUI cache from disk."""
    if os.path.isfile(_CACHE_FILE):
        try:
            with open(_CACHE_FILE) as f:
                return json.load(f)
        except Exception:
            pass
    return {}


def _save_cache(cache: dict[str, str]):
    """Save the OUI cache to disk."""
    os.makedirs(_CACHE_DIR, exist_ok=True)
    try:
        with open(_CACHE_FILE, "w") as f:
            json.dump(cache, f)
    except Exception:
        pass


def _online_lookup(oui: str) -> str:
    """Look up an OUI from macvendors.com API."""
    try:
        req = urllib.request.Request(
            f"https://api.macvendors.com/{oui}",
            headers={"User-Agent": "wlan-scan/1.0"},
        )
        with urllib.request.urlopen(req, timeout=1) as resp:
            body = resp.read().decode("utf-8").strip()
            if body and not body.startswith("{"):
                return body
    except Exception:
        pass
    return ""


def lookup_vendor(bssid: str) -> str:
    """Look up the vendor name from a BSSID (MAC address).

    Returns the vendor name if known, or empty string.
    """
    if not bssid or ":" not in bssid:
        return ""
    # Extract OUI: first 3 bytes, uppercase
    parts = bssid.strip().split(":")
    if len(parts) < 3:
        return ""
    oui = f"{parts[0].upper()}:{parts[1].upper()}:{parts[2].upper()}"

    # Check built-in database first
    builtin = _OUI_DB.get(oui, "")
    if builtin:
        return builtin

    # Check local cache
    cache = _load_cache()
    if oui in cache:
        return cache[oui]

    # Online fallback
    vendor = _online_lookup(oui)
    if vendor:
        cache[oui] = vendor
        _save_cache(cache)
        return vendor

    return ""
